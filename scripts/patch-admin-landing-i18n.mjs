function load(locale) {
  return JSON.parse(readFileSync(join(localesDir, `${locale}.json`), "utf8"));
}

function save(locale, data) {
  writeFileSync(join(localesDir, `${locale}.json`), `${JSON.stringify(data, null, 2)}\n`, "utf8");
}

function mergeAdmin(data, extras) {
  data.admin = { ...data.admin, ...extras };
}

