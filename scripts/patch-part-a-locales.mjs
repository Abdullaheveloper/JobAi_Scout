const locales = Object.fromEntries(
  codes.map((code) => [code, JSON.parse(readFileSync(join(localesDir, `${code}.json`), "utf8"))]),
);

// Ensure new keys exist in every locale (start from en defaults / en values)
for (const code of codes) {
  for (const [path, fallback] of Object.entries(NEW_KEY_DEFAULTS)) {
    const parts = path.split(".");
    let cur = locales.en;
    let missing = false;
    for (const part of parts) {
      if (cur == null || typeof cur !== "object" || !(part in cur)) {
        missing = true;
        break;
      }
      cur = cur[part];
    }
    const enVal = missing ? fallback : cur;
    let target = locales[code];
    for (let i = 0; i < parts.length - 1; i++) {
      if (!target[parts[i]] || typeof target[parts[i]] !== "object") target[parts[i]] = {};
      target = target[parts[i]];
    }
    const leaf = parts[parts.length - 1];
    if (target[leaf] === undefined) target[leaf] = enVal;
  }
}

// Apply translation overlays (overwrite English leftovers)
for (const [code, map] of Object.entries(TRANSLATIONS)) {
  for (const [path, value] of Object.entries(map)) {
    setPath(locales[code], path, value);
  }
}

for (const code of codes) {
  writeFileSync(join(localesDir, `${code}.json`), `${JSON.stringify(locales[code], null, 2)}\n`, "utf8");
  console.log(`Wrote ${code}.json`);
}

